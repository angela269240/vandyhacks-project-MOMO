#!/usr/bin/env node
// Start-of-session briefing for agents. Run by the SessionStart hook in .claude/settings.json; stdout becomes context.
// Read-only: never fetches, writes or changes git state. Safe to run by hand: `node claude/session-start.mjs`.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SESSIONS_DIR = "claude/sessions";

const git = (...args) => {
  try {
    return execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
};
const readJson = (rel) => {
  try {
    return JSON.parse(readFileSync(join(ROOT, rel), "utf8"));
  } catch {
    return null;
  }
};
const lines = (s) => (s ? s.split("\n").filter(Boolean) : []);
const out = [];
const say = (s = "") => out.push(s);

// ---------- git state ----------
const branch = git("rev-parse", "--abbrev-ref", "HEAD") || "(unknown)";
const head = git("log", "-1", "--format=%h %s");
const gitDir = git("rev-parse", "--git-dir");
const absGitDir = gitDir ? (gitDir.startsWith("/") ? gitDir : join(ROOT, gitDir)) : null;
const counts = (range) => {
  const r = git("rev-list", "--left-right", "--count", range);
  if (!r) return null;
  const [behind, ahead] = r.split(/\s+/).map(Number);
  return { ahead, behind };
};
const upstream = git("rev-parse", "--abbrev-ref", "--symbolic-full-name", "@{u}");
const vsUp = upstream ? counts(`${upstream}...HEAD`) : null;
const vsMain = counts("origin/main...HEAD");
const status = lines(git("status", "--porcelain"));
const staged = status.filter((l) => l[0] !== " " && l[0] !== "?").length;
const unstaged = status.filter((l) => l[1] !== " " && l[0] !== "?").length;
const untracked = status.filter((l) => l.startsWith("??")).length;
const conflicted = lines(git("diff", "--name-only", "--diff-filter=U"));
const changedFiles = status.map((l) => l.slice(3).replace(/^.* -> /, ""));

let op = null;
if (absGitDir) {
  if (existsSync(join(absGitDir, "MERGE_HEAD"))) op = "MERGE in progress";
  else if (existsSync(join(absGitDir, "rebase-merge")) || existsSync(join(absGitDir, "rebase-apply"))) op = "REBASE in progress";
  else if (existsSync(join(absGitDir, "CHERRY_PICK_HEAD"))) op = "CHERRY-PICK in progress";
  else if (existsSync(join(absGitDir, "REVERT_HEAD"))) op = "REVERT in progress";
}
let fetchedAgo = "never";
try {
  const ms = Date.now() - statSync(join(absGitDir, "FETCH_HEAD")).mtimeMs;
  fetchedAgo = ms < 3.6e6 ? `${Math.round(ms / 6e4)}m ago` : `${Math.round(ms / 3.6e6)}h ago`;
} catch {}

say("# Orbit agent briefing (auto-generated by claude/session-start.mjs)");
say("Protocol: claude/README.md. Facts: claude/project.json. Merge playbook: claude/conflicts.json.");
say();
say("## Git");
say(`- Branch \`${branch}\` @ ${head}`);
if (vsUp) say(`- vs ${upstream}: ${vsUp.ahead} ahead, ${vsUp.behind} behind`);
if (vsMain) say(`- vs origin/main: ${vsMain.ahead} ahead, ${vsMain.behind} behind (last fetch ${fetchedAgo}; run \`git fetch\` for fresh numbers)`);
say(`- Working tree: ${staged} staged, ${unstaged} unstaged, ${untracked} untracked`);
if (op) say(`- **${op}.** Finish or abort it before starting new work.`);

// ---------- conflicts ----------
const globToRe = (g) =>
  new RegExp(
    "^" +
      g
        .replace(/[.+^${}()|[\]\\]/g, "\\$&")
        .replace(/\*\*\/?/g, "\u0000")
        .replace(/\*/g, "[^/]*")
        .replace(/\?/g, "[^/]")
        .replace(/\u0000/g, ".*") +
      "(/.*)?$",
  );
const matches = (glob, file) => globToRe(glob).test(file);

if (conflicted.length) {
  const playbook = readJson("claude/conflicts.json");
  say();
  say(`## UNRESOLVED CONFLICTS (${conflicted.length}): follow claude/conflicts.json procedure`);
  for (const f of conflicted) {
    const rule = playbook?.rules?.find((r) => matches(r.path, f));
    say(`- ${f}${rule ? ` → [${rule.strategy}] ${rule.how}` : " → no rule: merge by hand, keep both sides' behavior"}`);
  }
}

// ---------- sessions (this checkout + every local/remote branch) ----------
const sessions = new Map(); // id -> { s, where }
const addSession = (s, where) => {
  if (!s || typeof s !== "object" || !s.id) return;
  const prev = sessions.get(s.id);
  // the working tree copy wins; otherwise keep the most recently updated looking copy
  if (!prev || where === "working tree" || (prev.where !== "working tree" && (s.ended ?? "") > (prev.s.ended ?? ""))) {
    sessions.set(s.id, { s, where });
  }
};
try {
  for (const f of readdirSync(join(ROOT, SESSIONS_DIR))) {
    if (f.endsWith(".json")) addSession(readJson(`${SESSIONS_DIR}/${f}`), "working tree");
  }
} catch {}
const refs = lines(git("for-each-ref", "--format=%(refname:short)", "refs/heads", "refs/remotes")).filter(
  (r) => !r.endsWith("/HEAD") && r !== "origin",
);
for (const ref of refs) {
  for (const path of lines(git("ls-tree", "-r", "--name-only", ref, "--", SESSIONS_DIR))) {
    if (!path.endsWith(".json")) continue;
    try {
      addSession(JSON.parse(git("show", `${ref}:${path}`)), ref);
    } catch {}
  }
}

const all = [...sessions.values()].sort((a, b) => (b.s.started ?? "").localeCompare(a.s.started ?? ""));
const live = all.filter(({ s }) => s.status === "active" || s.status === "paused");
const done = all.filter(({ s }) => s.status === "done").slice(0, 3);

say();
say(`## Open sessions (${live.length} active/paused across all branches)`);
if (!live.length) say("- none");
for (const { s, where } of live) {
  say(`- **${s.status}** \`${s.id}\` on \`${s.branch}\` by ${s.human ?? "?"} (seen in ${where})${s.uncommitted ? " [has UNCOMMITTED work]" : ""}`);
  say(`  - goal: ${s.goal}`);
  if (s.claims?.length) say(`  - claims: ${s.claims.join(", ")}`);
  if (s.next_steps?.length) say(`  - next: ${s.next_steps.slice(0, 3).join(" | ")}`);
  if (s.blockers?.length) say(`  - blockers: ${s.blockers.join(" | ")}`);
}

// overlap: files changed here vs claims of open sessions on other branches
const overlaps = [];
for (const { s } of live) {
  if (s.branch === branch) continue;
  for (const f of changedFiles) {
    const c = (s.claims ?? []).find((g) => matches(g, f));
    if (c) overlaps.push(`${f} ↔ ${s.id} (${s.branch}) claims ${c}`);
  }
}
if (overlaps.length) {
  say();
  say("## Claim overlaps (your changed files vs other open sessions): expect merge conflicts");
  for (const o of overlaps) say(`- ${o}`);
}

const resumable = live.filter(({ s }) => s.branch === branch && s.status === "paused");
if (resumable.length) {
  say();
  say(`## Resumable on this branch: ${resumable.map(({ s }) => s.id).join(", ")}`);
  say("Start a new session with `--continues <id>` and work from its next_steps.");
}

if (done.length) {
  say();
  say("## Recently finished");
  for (const { s } of done) say(`- \`${s.id}\` (${s.branch}): ${s.summary ?? s.goal}`);
}

// ---------- project facts ----------
const p = readJson("claude/project.json");
if (p) {
  say();
  say(`## Project facts (claude/project.json, updated ${p.updated})`);
  say(`- ${p.project?.name}: ${p.project?.scope}`);
  if (p.stack?.nextjs_warning) say(`- Next.js: ${p.stack.nextjs_warning}`);
  if (p.design?.current) say(`- Design: ${p.design.current} ${p.design.palette_status ?? ""}`.trim());
  say(`- Verify before handoff: ${(p.verify_before_handoff ?? []).join(" && ")}`);
  say("- Invariants:");
  for (const i of p.invariants ?? []) say(`  - ${i}`);
  say("- DANGER (ask the human first):");
  for (const d of p.danger ?? []) say(`  - \`${d.action}\`: ${d.why}`);
}

say();
say("## Your first steps");
say('1. `node claude/new-session.mjs "<goal>" --claim <path-or-glob> ...` to register this session (status active).');
say("2. Before ending: update your session file (status, summary, verification, next_steps) and commit it with your work.");

process.stdout.write(out.join("\n") + "\n");
